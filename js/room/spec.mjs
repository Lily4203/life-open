export const DESK  = { x: 1.555, z:-0.55, w:1.00, d:0.45, top:DESK_TOP, rot: Math.PI/2 };  // 右墙；前沿 x=1.33（她手腕 x1.350，落进去 2cm）
export const CHAIR = { x: 1.22, z:-0.55, w:0.40, d:0.30, seat:SEAT, back:0.52, rot: -Math.PI/2 }; // 背在 -x，她面朝 +x
