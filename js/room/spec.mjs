/* 她的尺寸和家具的尺寸 —— 全部来自实测，一个都不猜。
 * ============================================================
 * 单独成文件，因为它同时是三样东西的唯一出处：
 *   ① 建模（js/room/world.mjs 里按这些数去搭家具）
 *   ② 动作（room-bridge 算"走到床边"停在哪里、坐下沉多少）
 *   ③ 规矩（门 1.75、层高 2.05 是照她 1.357 反推的，换个高个子进来整间屋子都得重算）
 * 分成两份的后果实测过：桌面高度在一个地方改对了，另一个地方还是旧值，
 * 于是她"坐"下去的时候前臂穿进桌板——而这种错只有人眼能看出来。
 */

/* ============================================================
   一、她的尺寸 —— 全部来自实测，不猜
   诊断-VRM.html 的 window.__m() 量出来：总高 1.357，髋 0.441，
   膝 0.260，踝 0.078，肩 0.655，大腿 0.153，小腿 0.182，
   上臂 0.148，前臂 0.136，肩宽 0.180，髋宽 0.110。
   家具先从她反推：座面=膝高，桌面=坐着时的肘高。
   ============================================================ */
export const B = {
  h: 1.357,
  hipsY: 0.441, kneeY: 0.260, ankleY: 0.078,
  shoulderY: 0.655, headY: 0.741,
  thigh: 0.153, shin: 0.182,
  upperArm: 0.148, foreArm: 0.136,
  hipW: 0.110, shoulderW: 0.180, armSpan: 0.748,
};
export const SEAT = B.kneeY;                                             // 0.260 脚正好踩地
// 桌面高：实测坐姿肘高 0.404，桌面比肘低 4cm，前臂才是"搭"上去而不是端着。
// （一开始用公式 座面+躯干-上臂=0.335 推的，实测偏了 7cm，以实测为准）
export const DESK_TOP = 0.360;
export const SIT_DROP = +(SEAT - B.hipsY).toFixed(3);                    // -0.181 坐下时整体下沉

/* 房间按她的身高定：她 1.357，门 1.75，层高 2.05 —— 都比"真人尺度"小一号 */
